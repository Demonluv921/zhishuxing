// ============================================================
// Supabase 自动化配置脚本
// 用法: node scripts/setup-supabase.js <你的 Supabase 访问令牌>
// 令牌创建: https://supabase.com/dashboard/account/tokens (Generate new token)
// 功能:创建免费项目 -> 等待就绪 -> 建表+安全策略 -> 生成 supabase-config.json
// ============================================================
const https = require('https');
const fs = require('fs');
const path = require('path');

const token = process.argv[2];
if (!token) {
  console.error('用法: node scripts/setup-supabase.js <Supabase 访问令牌>');
  process.exit(1);
}

const API = 'https://api.supabase.com';
const projectName = 'zhishuxing';
const dbPass = randomPass(24);

function request(method, urlPath, body, authToken) {
  return new Promise((resolve, reject) => {
    const u = new URL(API + urlPath);
    const data = body ? JSON.stringify(body) : null;
    const req = https.request(u, {
      method,
      headers: {
        'Authorization': 'Bearer ' + authToken,
        'Content-Type': 'application/json',
        'User-Agent': 'zhishuxing-setup'
      }
    }, res => {
      let d = '';
      res.on('data', c => d += c);
      res.on('end', () => {
        let json = null;
        try { json = d ? JSON.parse(d) : null; } catch {}
        resolve({ status: res.statusCode, data: json, raw: d });
      });
    });
    req.on('error', reject);
    if (data) req.write(data);
    req.end();
  });
}

function randomPass(len) {
  const chars = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
  let s = '';
  for (let i = 0; i < len; i++) s += chars[Math.floor(Math.random() * chars.length)];
  return s;
}

const sleep = ms => new Promise(r => setTimeout(r, ms));

async function waitForProject(projectRef, authToken) {
  for (let i = 0; i < 40; i++) {
    await sleep(5000);
    const r = await request('GET', '/v1/projects/' + projectRef, null, authToken);
    if (r.status === 200 && r.data) {
      const status = r.data.status;
      console.log('  项目状态:', status);
      if (status === 'ACTIVE_HEALTHY') return true;
      if (status === 'COMING_UP') continue;
    }
  }
  return false;
}

async function main() {
  console.log('[1/4] 验证 Supabase 令牌...');
  const me = await request('GET', '/v1/projects', null, token);
  if (me.status !== 200) {
    console.error('令牌无效或权限不足:', me.status, me.raw);
    process.exit(1);
  }
  console.log('  已有项目数:', me.data.length);

  // 找已有项目(避免重复创建)
  let projectRef = null;
  for (const p of me.data) {
    if (p.name === projectName) { projectRef = p.id; console.log('  发现已存在项目', projectRef); break; }
  }
  if (!projectRef) {
    // 获取组织 slug
    const orgs = await request('GET', '/v1/organizations', null, token);
    if (orgs.status !== 200 || !orgs.data?.length) {
      console.error('获取组织失败:', orgs.status, orgs.raw);
      process.exit(1);
    }
    const orgSlug = orgs.data[0].slug;
    console.log('[2/4] 创建免费项目', projectName, '...');
    const create = await request('POST', '/v1/projects', {
      name: projectName,
      organization_slug: orgSlug,
      db_pass: dbPass,
      region: 'ap-southeast-1', // 新加坡,国内访问较快
    }, token);
    if (create.status !== 201 || !create.data?.id) {
      console.error('创建项目失败:', create.status, create.raw);
      process.exit(1);
    }
    projectRef = create.data.id;
    console.log('  项目创建中:', projectRef);
  }

  console.log('[3/4] 等待项目就绪(约 1-3 分钟)...');
  const ready = await waitForProject(projectRef, token);
  if (!ready) { console.error('项目长时间未就绪,请稍后在 Supabase 控制台确认'); process.exit(1); }

  // 获取 anon key
  const keys = await request('GET', `/v1/projects/${projectRef}/api-keys?reveal=true`, null, token);
  let anonKey = '';
  if (keys.status === 200 && Array.isArray(keys.data)) {
    const found = keys.data.find(k => k.name === 'anon');
    anonKey = found ? found.api_key : '';
  }
  if (!anonKey) { console.error('未能获取 anon key:', keys.raw); process.exit(1); }

  // 执行 SQL:建表 + 安全策略
  console.log('[4/4] 建表与安全策略...');
  const sql = `
CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account text UNIQUE NOT NULL,
  name text NOT NULL,
  salt text NOT NULL,
  pass_hash text NOT NULL,
  token text UNIQUE NOT NULL,
  created_at timestamptz DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.user_data (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token text UNIQUE NOT NULL REFERENCES public.users(token) ON DELETE CASCADE,
  data jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz DEFAULT now()
);
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_data ENABLE ROW LEVEL SECURITY;
-- 演示模式:客户端统一用 anon key 访问,账号隔离靠 token=eq.<token> 查询过滤;
-- 如需正式生产,应改用 Supabase Auth(JWT)+ auth.uid() 行级隔离。
DROP POLICY IF EXISTS "users_select_all" ON public.users;
CREATE POLICY "users_select_all" ON public.users
  FOR SELECT USING (true);
DROP POLICY IF EXISTS "users_insert_any" ON public.users;
CREATE POLICY "users_insert_any" ON public.users
  FOR INSERT WITH CHECK (true);
DROP POLICY IF EXISTS "user_data_all_any" ON public.user_data;
CREATE POLICY "user_data_all_any" ON public.user_data
  USING (true)
  WITH CHECK (true);
`;
  const res = await request('POST', `/v1/projects/${projectRef}/database/query`, { query: sql }, token);
  if (res.status !== 200 && res.status !== 201) {
    console.error('建表失败:', res.status, res.raw);
    process.exit(1);
  }

  // 生成配置文件
  const config = {
    url: `https://${projectRef}.supabase.co`,
    anonKey
  };
  fs.writeFileSync(path.join(__dirname, '..', 'supabase-config.json'), JSON.stringify(config, null, 2), 'utf8');
  console.log('');
  console.log('================== 完成 ==================');
  console.log('项目地址:', config.url);
  console.log('配置文件: supabase-config.json(已生成,已加入 .gitignore)');
  console.log('下一步: 重新构建并推送部署即可启用云同步');
}

main().catch(e => { console.error('执行出错:', e.message); process.exit(1); });
